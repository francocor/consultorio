import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  foreignKey,
  jsonb,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
} from 'drizzle-orm/pg-core';

import { tenantTable } from './_helpers.js';

/** Free-form JSON object columns (theme, settings). Their shapes are validated in the API. */
type JsonObject = Record<string, unknown>;

/**
 * The organization. Every other tenant table points here with `tenant_id`.
 *
 * Row level security uses `id` as the tenant column, so a tenant sees only its own row. A new row
 * is created under a context whose tenant id is the new id (the operator console does this; see
 * `createTenant`). `is_demo` is set at creation and never changes: a trigger rejects any update
 * that flips it (migration 0002).
 */
export const tenant = pgTable(
  'tenant',
  {
    id: uuid('id')
      .primaryKey()
      .default(sql`app.uuid_v7()`),
    /** Generated by the platform, never chosen by the visitor. Becomes the subdomain. */
    slug: text('slug').notNull(),
    /** Operational status, derived from the subscription: active, read_only or cancelled. */
    status: text('status').notNull().default('active'),
    readOnlySince: timestamp('read_only_since', { withTimezone: true }),
    isDemo: boolean('is_demo').notNull().default(false),
    billingExempt: boolean('billing_exempt').notNull().default(false),
    country: text('country').notNull().default('AR'),
    theme: jsonb('theme').$type<JsonObject>().notNull().default({}),
    settings: jsonb('settings').$type<JsonObject>().notNull().default({}),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true })
      .notNull()
      .defaultNow()
      .$onUpdate(() => new Date()),
  },
  (table) => [
    unique('tenant_slug_key').on(table.slug),
    check('tenant_slug_check', sql`${table.slug} ~ '^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])$'`),
    check('tenant_status_check', sql`${table.status} in ('active', 'read_only', 'cancelled')`),
    check(
      'tenant_read_only_since_check',
      sql`${table.status} <> 'read_only' or ${table.readOnlySince} is not null`,
    ),
  ],
);

export type Tenant = typeof tenant.$inferSelect;
export type NewTenant = typeof tenant.$inferInsert;

/**
 * A place where the organization attends. Its IANA time zone is authoritative for everything that
 * happens there; the tenant's country only supplies the default. Locations are deactivated, never
 * deleted, because appointments and cash days reference them.
 */
export const location = tenantTable(
  'location',
  {
    name: text('name').notNull(),
    timeZone: text('time_zone').notNull(),
    active: boolean('active').notNull().default(true),
  },
  (table) => [
    foreignKey({
      name: 'location_tenant_id_fkey',
      columns: [table.tenantId],
      foreignColumns: [tenant.id],
    }),
    check(
      'location_time_zone_check',
      sql`${table.timeZone} ~ '^(UTC|[A-Za-z]+(/[A-Za-z0-9_+-]+)+)$'`,
    ),
  ],
);

/** Per-tenant feature flag (plan entitlements and integrations are checked against it). */
export const tenantFeature = tenantTable(
  'tenant_feature',
  {
    feature: text('feature').notNull(),
    enabled: boolean('enabled').notNull().default(false),
  },
  (table) => [
    foreignKey({
      name: 'tenant_feature_tenant_id_fkey',
      columns: [table.tenantId],
      foreignColumns: [tenant.id],
    }),
    unique('tenant_feature_tenant_id_feature_key').on(table.tenantId, table.feature),
  ],
);
