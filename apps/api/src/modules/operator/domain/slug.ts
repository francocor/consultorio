/**
 * Words an organization may not use as its address: they name platform services or would be
 * confused with them (`platform.<base domain>` is the operator console).
 */
export const RESERVED_SLUGS: readonly string[] = [
  'admin',
  'api',
  'app',
  'assets',
  'docs',
  'login',
  'mail',
  'operator',
  'platform',
  'status',
  'static',
  'support',
  'www',
];

const MAX_BASE = 40;
const FALLBACK = 'organizacion';

/**
 * The address an organization gets from its name: lowercase letters and digits joined by single
 * hyphens, accents removed, at most 40 characters so a collision suffix always fits. The visitor
 * never chooses it (tenancy, "slug generated by the platform").
 */
export function slugBase(name: string): string {
  const words = name
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, MAX_BASE)
    .replace(/-+$/g, '');
  const base = words.length >= 2 ? words : FALLBACK;
  return RESERVED_SLUGS.includes(base) ? `${base}-org` : base;
}

/** The base plus a random suffix, used when the plain address is already taken. */
export function slugWithSuffix(base: string, suffix: string): string {
  return `${base}-${suffix}`;
}
