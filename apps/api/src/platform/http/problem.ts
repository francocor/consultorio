import { randomUUID } from 'node:crypto';
import { STATUS_CODES } from 'node:http';

import {
  ERROR_CATALOG,
  errorCodeForStatus,
  type ErrorCode,
  type FieldError,
  type Problem,
} from '@consultorio/contracts';
import type { FastifyError, FastifyInstance, FastifyReply, FastifyRequest } from 'fastify';
import { hasZodFastifySchemaValidationErrors } from 'fastify-type-provider-zod';

/** Media type of RFC 9457 problem details. */
export const PROBLEM_CONTENT_TYPE = 'application/problem+json';

/** Body of every error response. The shape lives in `@consultorio/contracts` so the web app shares it. */
export type ProblemBody = Problem;

/** Header that carries the request id back to the caller, for support and log correlation. */
export const REQUEST_ID_HEADER = 'x-request-id';

/** Generates the id attached to every request, log line and problem response. */
export function generateRequestId(): string {
  return randomUUID();
}

/**
 * An error the application raises on purpose. It carries a catalogued code and nothing else: the
 * message is never sent to the client, and the HTTP status comes from the catalog.
 */
export class AppError extends Error {
  readonly code: ErrorCode;

  constructor(code: ErrorCode) {
    super(code);
    this.name = 'AppError';
    this.code = code;
  }
}

/**
 * Echoes the request id in `x-request-id` on every response. The id is always generated by the
 * server (see `generateRequestId`); a value sent by the client is ignored so it cannot forge or
 * inject into log lines.
 */
export function registerRequestId(app: FastifyInstance): void {
  app.addHook('onSend', (request, reply, payload, done) => {
    void reply.header(REQUEST_ID_HEADER, request.id);
    done(null, payload);
  });
}

/** Keeps only the `at ...` lines of a stack: the first line of a V8 stack repeats the message. */
function stackFrames(stack: string | undefined): string[] {
  return (stack ?? '')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => line.startsWith('at '));
}

function sendProblem(
  request: FastifyRequest,
  reply: FastifyReply,
  code: ErrorCode,
  options: { errors?: FieldError[]; status?: number } = {},
): FastifyReply {
  const { i18nKey } = ERROR_CATALOG[code];
  // The catalog decides the status, except for a framework error (payload too large, unsupported
  // media type, ...) whose own 4xx status is kept so clients still see it.
  const status = options.status ?? ERROR_CATALOG[code].status;
  const body: ProblemBody = {
    type: 'about:blank',
    title: STATUS_CODES[status] ?? 'Error',
    status,
    code,
    i18nKey,
    requestId: request.id,
    ...(options.errors ? { errors: options.errors } : {}),
  };
  return reply.code(status).type(PROBLEM_CONTENT_TYPE).send(body);
}

/**
 * Denial of a tenant-scoped resource. A resource that does not exist and one the caller may not
 * see produce the SAME status and body (404 `not_found`), so the response cannot be used to find
 * out which resources exist (authorization, "Denials are uniform and non-leaking").
 */
export function denied(request: FastifyRequest, reply: FastifyReply): FastifyReply {
  return sendProblem(request, reply, 'not_found');
}

/**
 * Denial of a capability, such as a clinical route for a user without clinical access. It names no
 * resource, so a plain 403 reveals nothing about any record.
 */
export function forbidden(request: FastifyRequest, reply: FastifyReply): FastifyReply {
  return sendProblem(request, reply, 'forbidden');
}

function fieldErrors(error: FastifyError): FieldError[] {
  if (!hasZodFastifySchemaValidationErrors(error)) return [];
  return error.validation.map((issue) => ({
    // "/patient/name" -> "patient.name". The submitted value is never copied.
    path: issue.instancePath.replace(/^\//, '').replaceAll('/', '.') || '(root)',
    i18nKey: 'errors.field_invalid',
  }));
}

/**
 * Registers the 404 and error handlers.
 *
 * Responses are RFC 9457 problem+json carrying a catalogued code and the request id. The title
 * comes from the HTTP status phrase only: `error.message` is never sent to the client, because
 * messages from drivers and validators may contain data. The server-side log keeps the error name,
 * code and stack frames, but not the message, for the same reason.
 */
export function registerProblemHandlers(app: FastifyInstance): void {
  app.setNotFoundHandler((request, reply) => sendProblem(request, reply, 'not_found'));

  app.setErrorHandler((error: FastifyError, request, reply) => {
    const frameworkStatus =
      typeof error.statusCode === 'number' && error.statusCode >= 400 && error.statusCode < 600
        ? error.statusCode
        : 500;
    const code: ErrorCode =
      error instanceof AppError
        ? error.code
        : hasZodFastifySchemaValidationErrors(error)
          ? 'validation_failed'
          : errorCodeForStatus(frameworkStatus);
    const fromFramework =
      !(error instanceof AppError) && !hasZodFastifySchemaValidationErrors(error);
    const status = fromFramework ? frameworkStatus : ERROR_CATALOG[code].status;

    const failure = { name: error.name, code: error.code, frames: stackFrames(error.stack) };
    if (status >= 500) {
      request.log.error({ failure }, 'request failed');
    } else {
      request.log.info({ failure: { name: error.name, code: error.code } }, 'request rejected');
    }

    const errors = code === 'validation_failed' ? fieldErrors(error) : [];
    return sendProblem(request, reply, code, {
      status,
      ...(errors.length > 0 ? { errors } : {}),
    });
  });
}
